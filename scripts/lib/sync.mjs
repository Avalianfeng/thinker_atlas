/**
 * 遗留同步库。CLI 默认禁用（见 scripts/sync.mjs）。展馆真源 = git content/。
 */
import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir, readdir, rm } from 'node:fs/promises';
import path from 'node:path';
import { atlasRefsOf, titleOf, bodyOf } from './notes.mjs';

export const JOURNAL_DIR = 'atlas';
export const INDEX_DIR = 'atlas/_index';
export const CACHE_DIR = 'content/sb-cache';
const STATE_VERSION = 1;
const GENERATED_MARK = '<!-- generated by atlas: 由 Atlas 生成，勿改。下次同步会覆盖。 -->';

export const sha = (s) => createHash('sha256').update(s, 'utf8').digest('hex');

/** 笔记在 Atlas 里的只读页面地址：notes/<路径>/，逐段编码。 */
export const noteUrl = (siteUrl, page) =>
  `${siteUrl.replace(/\/$/, '')}/notes/${page
    .replace(/\.md$/, '')
    .replace(/^notes\//, '')
    .split('/')
    .map(encodeURIComponent)
    .join('/')}/`;

/** 笔记路径 → 本地随笔文件名：atlas/读书/维特根斯坦.md → 读书/维特根斯坦.md */
export const journalRelOf = (page) => page.replace(/^atlas\//, '');

async function readMaybe(file) {
  try {
    return await readFile(file, 'utf8');
  } catch {
    return null;
  }
}

async function walkMd(dir, base = dir, acc = []) {
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return acc;
  }
  for (const e of entries) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) await walkMd(p, base, acc);
    else if (/\.mdx?$/.test(e.name)) acc.push(path.relative(base, p).split(path.sep).join('/'));
  }
  return acc;
}

export async function loadState(statePath) {
  const raw = await readMaybe(statePath);
  if (!raw) return { version: STATE_VERSION, files: {} };
  try {
    const s = JSON.parse(raw);
    return { version: s.version ?? STATE_VERSION, files: s.files ?? {} };
  } catch {
    return { version: STATE_VERSION, files: {} };
  }
}

export async function saveState(statePath, state) {
  await mkdir(path.dirname(statePath), { recursive: true });
  await writeFile(statePath, JSON.stringify({ version: STATE_VERSION, files: sortKeys(state.files) }, null, 2) + '\n');
}

const sortKeys = (o) =>
  Object.fromEntries(Object.keys(o).sort().map((k) => [k, Object.fromEntries(Object.entries(o[k]).sort())]));

/**
 * 双向同步：SilverBullet 的 atlas/ ⇄ 本地 content/journal/。
 * 规则（见方案 §8）：记录上次同步时的哈希；只有一边变了就同步；两边都变则判冲突，
 * 不覆盖，把对方版本写成 xxx.conflict.md 并提示手动合并。删除不自动同步，只提示。
 */
export async function syncJournal({ adapter, contentDir, state, dryRun = false }) {
  const statePath = path.join(contentDir, '..', 'sync', 'state.json');
  const journalDir = path.join(contentDir, 'journal');
  await mkdir(journalDir, { recursive: true });

  const notes = await adapter.list(JOURNAL_DIR);
  const remote = new Map();
  for (const n of notes) {
    const rel = journalRelOf(n.page);
    if (!rel || rel.startsWith('_index/') || rel === '_index.md') continue;
    remote.set(rel, n);
  }

  const localFiles = (await walkMd(journalDir)).filter((f) => !f.endsWith('.conflict.md'));
  const local = new Map(localFiles.map((f) => [f, path.join(journalDir, f)]));

  const result = { pulled: [], pushed: [], conflicts: [], unchanged: 0, deleted: [], created: [] };
  const nextFiles = { ...state.files };
  const seen = new Set();

  for (const rel of [...new Set([...remote.keys(), ...local.keys()])].sort()) {
    seen.add(rel);
    const note = remote.get(rel);
    const localPath = local.get(rel);
    const localContent = localPath ? await readMaybe(localPath) : null;
    const remoteContent = note ? note.content : null;
    const prev = state.files[rel];

    const localHash = localContent === null ? null : sha(localContent);
    const remoteHash = remoteContent === null ? null : sha(remoteContent);

    // 只存在于 SilverBullet
    if (localContent === null && remoteContent !== null) {
      if (!dryRun) {
        await mkdir(path.dirname(localPath ?? path.join(journalDir, rel)), { recursive: true });
        await writeFile(path.join(journalDir, rel), remoteContent);
      }
      result.pulled.push(rel);
      nextFiles[rel] = { note: `${JOURNAL_DIR}/${rel}`, hash: remoteHash, syncedAt: new Date().toISOString() };
      continue;
    }
    // 只存在于本地
    if (remoteContent === null && localContent !== null) {
      if (prev && prev.hash) {
        // 曾经同步过、现在远端不见了：不自动删除，也不自动重建，提示人工处理
        result.deleted.push(rel);
        continue;
      }
      if (!dryRun) await adapter.write(`${JOURNAL_DIR}/${rel}`, localContent);
      result.pushed.push(rel);
      nextFiles[rel] = { note: `${JOURNAL_DIR}/${rel}`, hash: localHash, syncedAt: new Date().toISOString() };
      continue;
    }
    if (localContent === null || remoteContent === null) continue;

    if (localHash === remoteHash) {
      result.unchanged += 1;
      nextFiles[rel] = { note: `${JOURNAL_DIR}/${rel}`, hash: localHash, syncedAt: prev?.syncedAt ?? new Date().toISOString() };
      continue;
    }

    if (!prev) {
      // 两边各自独立存在同名文件：按冲突处理，绝不以一边覆盖另一边
      const conflictPath = path.join(journalDir, rel.replace(/\.md$/, '.conflict.md'));
      if (!dryRun) {
        await writeFile(
          conflictPath,
          `<!-- 冲突：来自 SilverBullet 的 ${JOURNAL_DIR}/${rel}。本地版本保留在原文件。请手动合并后删除本文件。 -->\n\n${remoteContent}`,
        );
      }
      result.conflicts.push({ rel, conflictPath });
      continue;
    }

    const localChanged = localHash !== prev.hash;
    const remoteChanged = remoteHash !== prev.hash;

    if (localChanged && !remoteChanged) {
      if (!dryRun) await adapter.write(`${JOURNAL_DIR}/${rel}`, localContent);
      result.pushed.push(rel);
      nextFiles[rel] = { note: `${JOURNAL_DIR}/${rel}`, hash: localHash, syncedAt: new Date().toISOString() };
    } else if (!localChanged && remoteChanged) {
      if (!dryRun) await writeFile(path.join(journalDir, rel), remoteContent);
      result.pulled.push(rel);
      nextFiles[rel] = { note: `${JOURNAL_DIR}/${rel}`, hash: remoteHash, syncedAt: new Date().toISOString() };
    } else {
      const conflictPath = path.join(journalDir, rel.replace(/\.md$/, '.conflict.md'));
      if (!dryRun) {
        await writeFile(
          conflictPath,
          `<!-- 冲突：两边都改过。此文件是 SilverBullet 的版本（${JOURNAL_DIR}/${rel}）；本地版本保留在原名文件。请手动合并后删除本文件。 -->\n\n${remoteContent}`,
        );
      }
      result.conflicts.push({ rel, conflictPath });
      // 状态不前进：冲突未解决前，下次同步仍会提示
    }
  }

  // 曾同步过、这次两边都不见了：只提示
  for (const rel of Object.keys(state.files)) {
    if (!seen.has(rel)) result.deleted.push(rel);
  }

  if (!dryRun) await saveState(statePath, { version: STATE_VERSION, files: nextFiles });
  return result;
}

/**
 * 引用拉取：任意笔记只要 frontmatter 有 atlas: 或标签 #atlas/<人物>，
 * 就缓存到 content/sb-cache/，供「相关笔记」栏与 <SBNote> 嵌入使用。
 * 原笔记永远只在 SilverBullet 里改，所以这里每次全量覆盖。
 */
export async function syncReferences({ adapter, contentDir, siteUrl = '', dryRun = false }) {
  const all = await adapter.list('');
  const refs = [];
  const cacheDir = path.join(contentDir, 'sb-cache');
  const written = [];

  for (const note of all) {
    if (note.page.startsWith(JOURNAL_DIR + '/')) continue; // 双向区单独处理
    const ids = atlasRefsOf(note);
    if (!ids.length) continue;
    refs.push({ page: note.page, ids });
    const target = path.join(cacheDir, note.page.replace(/\.md$/, '.md'));
    const front = [
      '---',
      `page: ${JSON.stringify(note.page)}`,
      `title: ${JSON.stringify(titleOf(note))}`,
      `atlas: [${ids.map((i) => JSON.stringify(i)).join(', ')}]`,
      `lastModified: ${note.lastModified ?? 0}`,
      `url: ${JSON.stringify(noteUrl(siteUrl, note.page))}`,
      '---',
      '',
    ].join('\n');
    if (!dryRun) {
      await mkdir(path.dirname(target), { recursive: true });
      await writeFile(target, front + bodyOf(note.content));
    }
    written.push(note.page);
  }

  // 清掉已不再被引用的缓存
  if (!dryRun) {
    const keep = new Set(written);
    for (const f of await walkMd(cacheDir)) if (!keep.has(f)) await rm(path.join(cacheDir, f));
  }
  return { refs, written };
}

/**
 * 入口页生成：Atlas → SilverBullet，单向。每人一篇，概念各自一篇，
 * 顶部带生成标记；遇到没有标记的同名文件则跳过并警告（不覆盖手写内容）。
 */
export async function generateIndexPages({ adapter, atlas, siteUrl = '', dryRun = false, log = console.log }) {
  const written = [];
  const skipped = [];

  const thinkers = atlas?.thinkers ?? [];
  if (!thinkers.length) return { written, skipped };

  const put = async (page, content) => {
    const existing = await adapter.read(page);
    if (existing && !existing.content.startsWith(GENERATED_MARK)) {
      skipped.push(page);
      log(`跳过（非生成文件）：${page}`);
      return;
    }
    if (!dryRun) await adapter.write(page, content);
    written.push(page);
  };

  for (const t of thinkers) {
    const concepts = (atlas.concepts ?? []).filter((c) => c.data.id.startsWith(t.id + '/'));
    const works = (atlas.works ?? []).filter((w) => w.data.id.startsWith(t.id + '/'));
    const site = `${siteUrl.replace(/\/$/, '')}/thinkers/${t.id.replace('atlas:', '')}/`;
    const lines = [
      GENERATED_MARK,
      `# ${t.data.name.zh}`,
      '',
      `> ${t.data.name.zh}（${t.data.name.original || t.data.name.en}，${String(t.data.born?.date ?? '').slice(0, 4)}—${String(t.data.died?.date ?? '').slice(0, 4)}）· 成熟度：${t.data.maturity}`,
      '',
      t.data.intro,
      '',
      '## 概念',
      ...(concepts.length ? concepts.map((c) => `- ${c.data.title}${c.data.original ? `（${c.data.original}）` : ''}：${c.data.definition}`) : ['- （暂无）']),
      '',
      '## 作品',
      ...(works.length ? works.map((w) => `- ${w.data.title}（${w.data.year}）`) : ['- （暂无）']),
      '',
      `网站：${site}`,
      '',
    ];
    await put(`${INDEX_DIR}/${t.data.name.zh}.md`, lines.join('\n'));

    for (const c of concepts) {
      const csite = `${siteUrl.replace(/\/$/, '')}/thinkers/${t.id.replace('atlas:', '')}/thought/${c.data.id.split('/')[1]}/`;
      await put(
        `${INDEX_DIR}/${t.data.name.zh}/${c.data.title}.md`,
        [
          GENERATED_MARK,
          `# ${c.data.title}`,
          '',
          `> ${t.data.name.zh} · ${c.data.original ?? ''}`,
          '',
          c.data.definition,
          '',
          c.data.questions?.length ? '## 它要回答的问题\n' + c.data.questions.map((q) => `- ${q}`).join('\n') : '',
          '',
          `网站：${csite}`,
          `返回：[[${INDEX_DIR}/${t.data.name.zh}]]`,
          '',
        ].join('\n'),
      );
    }
  }
  return { written, skipped };
}

/** 组装一份给入口页生成器用的轻量 atlas（从 content/ 读，不依赖 Astro 运行时）。 */
export async function loadAtlasSnapshot(contentDir) {
  const { parse } = await import('./frontmatter.mjs');
  const thinkersDir = path.join(contentDir, 'thinkers');
  const thinkers = [];
  const concepts = [];
  const works = [];
  let slugs = [];
  try {
    slugs = (await readdir(thinkersDir, { withFileTypes: true })).filter((e) => e.isDirectory()).map((e) => e.name);
  } catch {
    slugs = [];
  }
  for (const slug of slugs) {
    const idx = await readMaybe(path.join(thinkersDir, slug, 'index.md')) ?? (await readMaybe(path.join(thinkersDir, slug, 'index.mdx')));
    if (!idx) continue;
    const { data } = parse(idx);
    thinkers.push({ id: data.id ?? `atlas:${slug}`, data });
    for (const f of await walkMd(path.join(thinkersDir, slug, 'thought'))) {
      const raw = await readMaybe(path.join(thinkersDir, slug, 'thought', f));
      if (raw) concepts.push({ id: parse(raw).data.id, data: parse(raw).data });
    }
    for (const f of await walkMd(path.join(thinkersDir, slug, 'works'))) {
      const raw = await readMaybe(path.join(thinkersDir, slug, 'works', f));
      if (raw) works.push({ id: parse(raw).data.id, data: parse(raw).data });
    }
  }
  return { thinkers, concepts, works };
}
